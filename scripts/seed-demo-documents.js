// ─── HTTP ──────────────────────────────────────────────────────────────

let token = null;

async function api(method, route, body, { raw = false } = {}) {
  const headers = { Accept: 'application/json' };
  if (token) headers.Authorization = `Bearer ${token}`;
  if (body && !raw) headers['Content-Type'] = 'application/json';

  const res = await fetch(`${API}${route}`, {
    method,
    headers,
    body: raw ? body : body ? JSON.stringify(body) : undefined,
  });

  const text = await res.text();
  let json = null;
  try {
    json = JSON.parse(text);
  } catch {
    /* non-JSON error page; keep the text for the message below */
  }

  if (!res.ok) {
    const detail = json?.error?.message || text.slice(0, 300);
    throw new Error(`${method} ${route} -> ${res.status}: ${detail}`);
  }
  // Every response is the { data, meta, error } envelope.
  return json?.data ?? json;
}

async function login() {
  if (!PASSWORD) {
    throw new Error('SEED_PASSWORD is required (SEED_EMAIL defaults to the sweep demo account)');
  }
  const data = await api('POST', '/auth/login', {
    email: EMAIL,
    password: PASSWORD,
  });
  token = data.access_token;
  if (!token) throw new Error('login returned no access_token');
  return data;
}

/** Existing document names, so a re-run tops up rather than duplicates. */
async function existingDocumentNames() {
  const names = new Set();
  for (let page = 1; page <= 20; page++) {
    const rows = await api('GET', `/documents?page=${page}&limit=100`);
    const list = Array.isArray(rows) ? rows : rows?.items || [];
    list.forEach((d) => names.add(d.name));
    if (list.length < 100) break;
  }
  return names;
}

async function findOrCreatePerson(a) {
  const found = await api(
    'GET',
    `/crm/entities?type=person&search=${encodeURIComponent(a.email)}&limit=5`,
  );
  const list = Array.isArray(found) ? found : found?.items || [];
  const hit = list.find((e) => e.email === a.email);
  if (hit) return hit;

  return api('POST', '/crm/entities', {
    type: 'person',
    firstName: a.firstName,
    lastName: a.lastName,
    email: a.email,
    phoneNumber: a.phoneNumber,
    verticalAttributes: {
      nationality: a.nationality,
      passportNumber: a.passportNumber,
      dateOfBirth: a.dateOfBirth,
      occupation: a.occupation,
      anzscoCode: a.anzsco,
      visaSubclass: a.caseTitle,
      source: 'seed-demo-documents',
      specimen: true,
    },
  });
}

async function uploadDocument({ name, fileName, buffer, person, docKey }) {
  const form = new FormData();
  form.append('file', new Blob([buffer], { type: 'application/pdf' }), fileName);
  form.append('name', name);
  form.append('fileType', 'pdf');
  form.append('tags', 'demo');
  form.append('tags', 'specimen');
  if (docKey) form.append('tags', docKey);
  form.append(
    'metadata',
    JSON.stringify({
      specimen: true,
      documentType: docKey || 'firm',
      seededBy: 'scripts/seed-demo-documents.js',
    }),
  );
  if (person) {
    form.append('linkedEntityType', 'crm_entity');
    form.append('linkedEntityId', person.id);
  }

  return api('POST', '/documents/upload', form, { raw: true });
}

// ─── Main ──────────────────────────────────────────────────────────────

async function main() {
  const planned = [];

  for (const a of APPLICANTS) {
    for (const key of a.docs) {
      const built = BUILDERS[key](a);
      planned.push({ ...built, applicant: a, docKey: key });
    }
  }
  planned.push(...FIRM_DOCS.map((d) => ({ ...d, applicant: null, docKey: null })));

  if (DRY_RUN) {
    fs.mkdirSync(OUT_DIR, { recursive: true });
    for (const d of planned) {
      fs.writeFileSync(
        path.join(OUT_DIR, d.fileName),
        buildPdf({ ...d.pdf, footer: SPECIMEN }),
      );
    }
    console.log(`Wrote ${planned.length} PDFs to ${OUT_DIR} (uploaded nothing).`);
    return;
  }

  console.log(`Target: ${API}`);
  const session = await login();
  console.log(`Signed in as ${EMAIL} (tenant ${session.tenant_id})`);

  const already = await existingDocumentNames();
  console.log(`${already.size} document(s) already present.`);

  const people = new Map();
  for (const a of APPLICANTS) {
    // Create the person even if all their documents already exist — the demo
    // needs the client list populated, not just the document list.
    const person = await findOrCreatePerson(a);
    people.set(a.key, person);
    console.log(`  person ${a.firstName} ${a.lastName} -> ${person.id}`);
  }

  let uploaded = 0;
  let skipped = 0;
  const failures = [];

  for (const d of planned) {
    if (already.has(d.name)) {
      skipped++;
      continue;
    }
    const buffer = buildPdf({ ...d.pdf, footer: SPECIMEN });
    try {
      const doc = await uploadDocument({
        name: d.name,
        fileName: d.fileName,
        buffer,
        person: d.applicant ? people.get(d.applicant.key) : null,
        docKey: d.docKey,
      });
      uploaded++;
      console.log(`  uploaded ${d.name} (${buffer.length} bytes) -> ${doc?.id ?? 'ok'}`);
    } catch (e) {
      failures.push(`${d.name}: ${e.message}`);
      console.error(`  FAILED  ${d.name}: ${e.message}`);
    }
  }

  console.log(
    `\n${uploaded} uploaded, ${skipped} already present, ${failures.length} failed.`,
  );
  if (failures.length) process.exitCode = 1;
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
