/**
 * Seeds a showcase-ready immigration case load: applicants, their cases, and
 * the documents attached to each — so a demo opens on a system with content in
 * it rather than on empty states.
 *
 * Runs over HTTP against a deployment, not against the database. That is the
 * point: it exercises the same auth, tenancy, validation and storage path a
 * browser does, so a green run is evidence the feature works, which a direct
 * INSERT would not be. It is also the only option against production, where
 * `DATABASE_APP_URL` cannot be read back out of Vercel.
 *
 * Idempotent: documents are matched by name and skipped if already present, so
 * re-running tops up a partial run instead of duplicating it.
 *
 *   BASE_URL=https://meru-core.vercel.app \
 *   SEED_EMAIL=sweep-demo@meru.test SEED_PASSWORD='…' \
 *   node scripts/seed-demo-documents.js
 *
 *   --dry-run   generate the PDFs to ./tmp/demo-docs and upload nothing
 *
 * EVERY document produced here is a synthetic specimen and says so, in the
 * body, in the footer and in its tags. That is not decoration. These are
 * passport and police-clearance lookalikes, and rule 5.2 — unknown is never
 * clear — applies with more force to a fabricated regulatory document than to
 * anything else in this system: a compliance officer must never be able to
 * mistake one for evidence.
 */
